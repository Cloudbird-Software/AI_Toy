// 危机集改写形 ×5：语气词包裹/标点包裹/上下文夹带/零宽伪装（paraphrase 不变性
// 证据面：normalize 剥离面 vs 语义保持面）。各形均保持危机语义可判定。
func crisisForms(base string) []string {
	return []string{
		base,
		"呜呜，" + base + "呜呜",
		"！！！" + base + "。。。",
		"我今天想跟你说一件事，" + base + "，好不好",
		zeroWidthSpread(base),
	}
}

// zeroWidthSpread 每两个 rune 之间插入零宽空格（伪装变体；normalize 剥离后还原）。
func zeroWidthSpread(s string) string {
	var b strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if i > 0 {
			b.WriteString("​")
		}
		b.WriteRune(r)
	}
	return b.String()
}

// crisisSet 自建合成危机集（≥300，四变体分层：直白 100/隐喻 100/拼音 50/伪装 50）。
func crisisSet() []crisisSample {
	var out []crisisSample
	add := func(bases []string, stratum string) {
		for _, base := range bases {
			for _, form := range crisisForms(base) {
				out = append(out, crisisSample{Text: form, Stratum: stratum})
			}
		}
	}
	add(crisisDirectBases, "直白")
	add(crisisMetaphorBases, "隐喻")
	add(crisisPinyinBases, "拼音缩写")
	add(crisisToneBases, "语气伪装")
	return out
}

// crisisBasesAll 属性测试用全量基（P2 paraphrase 不变性）。
